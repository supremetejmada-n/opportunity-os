import assert from 'assert';
import {
  getCanonicalOpportunityKey,
  areSemanticallyDuplicate,
  normalizeTitleText,
  inferServiceCategory,
  inferCustomerArchetype
} from '../server/services/canonicalIdentity.js';
import { opportunityEngine } from '../server/services/opportunityEngine.js';
import { generateAndStoreCombinations } from '../server/services/combineEngine.js';
import { cleanExistingDuplicates } from '../server/services/opportunityCleanup.js';
import { initDatabase, dbRun, dbGet, dbAll } from '../server/db/sqlite.js';

async function runDeduplicationRegressionTests() {
  console.log('====================================================');
  console.log(' Running Opportunity OS Deduplication Test Suite');
  console.log('====================================================');

  await initDatabase();

  // Test 1: Same title with different capitalization → duplicate
  console.log('\n[Test 1] Capitalization normalization...');
  const key1a = getCanonicalOpportunityKey({ title: 'AI SOCIAL MEDIA POST GENERATOR FOR SMALL BUSINESSES' });
  const key1b = getCanonicalOpportunityKey({ title: 'ai social media post generator for small businesses' });
  assert.strictEqual(key1a, key1b, 'Capitalization difference must produce the exact same canonical key');
  console.log('✓ Passed');

  // Test 2: Same service with different wording → duplicate
  console.log('\n[Test 2] Equivalent service wording normalization...');
  const key2a = getCanonicalOpportunityKey({
    title: 'AI Social Media Post Generator for Small Businesses',
    customerType: 'Small Businesses'
  });
  const key2b = getCanonicalOpportunityKey({
    title: 'Social Media Content Creation Service for Small Business Owners',
    customerType: 'Small Business Owners'
  });
  assert.strictEqual(key2a, key2b, 'Equivalent service wording must yield the exact same canonical key');
  console.log('✓ Passed');

  // Test 3: Generic title prefix changed → duplicate
  console.log('\n[Test 3] Generic title prefix removal...');
  const norm3a = normalizeTitleText('Create an automated Social Media Content Service');
  const norm3b = normalizeTitleText('Automated AI-Powered Social Media Content Service');
  assert.strictEqual(norm3a, norm3b, 'Fluff title prefixes must be stripped in normalization');
  console.log('✓ Passed');

  // Test 4: Same service with a different customer synonym → duplicate when underlying service is unchanged
  console.log('\n[Test 4] Customer synonym normalization...');
  const key4a = getCanonicalOpportunityKey({
    title: 'AI Poster Packages for Local Shops',
    targetCustomer: 'Local Shops'
  });
  const key4b = getCanonicalOpportunityKey({
    title: 'AI Poster Packages for Retailers and Small Businesses',
    targetCustomer: 'Small Businesses'
  });
  assert.strictEqual(key4a, key4b, 'Synonymous customer descriptions (Shops vs Small Businesses) must yield same key');
  console.log('✓ Passed');

  // Test 5: Same discovery scanned twice → no duplicate opportunity
  console.log('\n[Test 5] Scanning idempotency (no duplicates on repeated evaluation)...');
  const initialOpps = await opportunityEngine.evaluateOpportunities();
  const countBefore = initialOpps.length;

  const repeatOpps = await opportunityEngine.evaluateOpportunities();
  const countAfter = repeatOpps.length;

  assert.strictEqual(countBefore, countAfter, 'Re-evaluating opportunities must not create extra database records');
  console.log(`✓ Passed (Kept strictly ${countAfter} distinct canonical opportunities)`);

  // Test 6: Same service generated by different tool stacks → one canonical opportunity when outcomes are equivalent
  console.log('\n[Test 6] Tool stack variation deduplication in Combine Tools...');
  const combos = await generateAndStoreCombinations({ forceRefresh: true });
  const keys = combos.map(c => c.canonical_key);
  const uniqueKeys = new Set(keys);
  assert.strictEqual(keys.length, uniqueKeys.size, 'Combine Tools must produce 1 canonical opportunity per unique deliverable');
  console.log(`✓ Passed (Generated ${combos.length} unique tool combinations with 0 duplicate keys)`);

  // Test 7: Different services for the same audience → retained
  console.log('\n[Test 7] Distinct services for same audience retained...');
  const keyGraphics = getCanonicalOpportunityKey({
    title: 'Local Business AI Poster & Graphic Packages',
    summary: 'Design promotional posters and social banners for local cafes',
    customerType: 'Local Businesses'
  });
  const keyVideo = getCanonicalOpportunityKey({
    title: 'Short-Form Instagram Reels Creation Service',
    summary: 'Produce short-form video reels and video clips for local cafes',
    customerType: 'Local Businesses'
  });
  assert.notStrictEqual(keyGraphics, keyVideo, 'Graphic design and video editing for local business must be retained as distinct services');
  console.log('✓ Passed');

  // Test 8: Similar titles but different deliverables → retained
  console.log('\n[Test 8] Similar titles with different deliverables retained...');
  const keyLeadTriage = getCanonicalOpportunityKey({
    title: 'Customer Lead & Response Automation',
    summary: 'Build n8n form listener to triage incoming customer leads'
  });
  const keyDocAuditor = getCanonicalOpportunityKey({
    title: 'Confidential Document & Contract Auditor',
    summary: 'Analyze legal PDFs offline with Ollama'
  });
  assert.notStrictEqual(keyLeadTriage, keyDocAuditor, 'Lead triage bot and document auditor must remain distinct');
  console.log('✓ Passed');

  // Test 9: Distinct workflows with different outcomes → retained
  console.log('\n[Test 9] Distinct workflows with different outcomes retained...');
  const catLead = inferServiceCategory({ title: 'n8n Lead Response Bot', workflow: ['n8n', 'Gemini'] });
  const catDoc = inferServiceCategory({ title: 'Ollama PDF Reader', workflow: ['Ollama', 'Python'] });
  assert.notStrictEqual(catLead, catDoc, 'Different workflows must map to distinct categories');
  console.log('✓ Passed');

  // Test 10: Repeated and concurrent generation → no duplicate records
  console.log('\n[Test 10] Concurrent evaluation safety...');
  await Promise.all([
    opportunityEngine.evaluateOpportunities(),
    opportunityEngine.evaluateOpportunities()
  ]);
  const postConcurrentOpps = await opportunityEngine.getOpportunities();
  const concurrentKeys = postConcurrentOpps.map(o => o.canonicalKey);
  assert.strictEqual(concurrentKeys.length, new Set(concurrentKeys).size, 'Concurrent requests must not introduce duplicates');
  console.log('✓ Passed');

  // Test 11: Existing action plans and progress → preserved after cleanup
  console.log('\n[Test 11] Action plan and progress preservation during cleanup...');
  // Insert a test canonical opportunity and a duplicate
  const testId1 = 'test_opp_primary_123';
  const testId2 = 'test_opp_duplicate_456';
  const testKey = 'canonical::SOCIAL_MEDIA_GRAPHICS::LOCAL_BUSINESS';

  await dbRun('DELETE FROM opportunities WHERE id IN (?, ?);', [testId1, testId2]);
  await dbRun('DELETE FROM action_plans WHERE opportunity_id IN (?, ?);', [testId1, testId2]);

  await dbRun(`
    INSERT INTO opportunities (id, title, summary, customer_type, score, canonical_key, saved)
    VALUES (?, 'Social Graphics Pack', 'Primary opp', 'Local Businesses', 85, ?, 1);
  `, [testId1, testKey]);

  await dbRun(`
    INSERT INTO opportunities (id, title, summary, customer_type, score, canonical_key, saved)
    VALUES (?, 'Social Media Posts for Shops', 'Duplicate opp', 'Local Businesses', 80, ?, 0);
  `, [testId2, testKey]);

  // Attach action plan to duplicate ID to test reference migration
  const planId = 'test_plan_789';
  await dbRun('DELETE FROM action_plans WHERE id = ?;', [planId]);
  await dbRun(`
    INSERT INTO action_plans (id, opportunity_id, title, objective)
    VALUES (?, ?, 'Test Action Plan', 'Build templates');
  `, [planId, testId2]);

  // Execute cleanup
  const cleanupStats = await cleanExistingDuplicates();
  
  // Verify reference migrated to testId1
  const updatedPlan = await dbGet<any>('SELECT opportunity_id FROM action_plans WHERE id = ?;', [planId]);
  assert.strictEqual(updatedPlan.opportunity_id, testId1, 'Action plan must be migrated to the primary canonical record ID');
  
  // Clean up test records
  await dbRun('DELETE FROM action_plans WHERE id = ?;', [planId]);
  await dbRun('DELETE FROM opportunities WHERE id = ?;', [testId1]);
  console.log(`✓ Passed (Cleaned up ${cleanupStats.oppClustersFound} clusters, merged ${cleanupStats.oppRecordsMerged} records, preserved action plan reference)`);

  // Test 12: Unknown cost and evidence → preserved accurately
  console.log('\n[Test 12] Unknown cost and evidence preservation...');
  const oppWithEvidence = await opportunityEngine.getOpportunityById('opp-poster-packages');
  if (oppWithEvidence) {
    assert.strictEqual(typeof oppWithEvidence.evidence, 'object', 'Evidence must be preserved as object');
    assert.strictEqual(typeof oppWithEvidence.startupCost, 'number', 'Startup cost must be preserved as number');
  }
  console.log('✓ Passed');

  console.log('\n====================================================');
  console.log(' ALL 12 REGRESSION TESTS PASSED SUCCESSFULLY! ');
  console.log('====================================================\n');
}

runDeduplicationRegressionTests().catch(err => {
  console.error('Test Suite Failed:', err);
  process.exit(1);
});
